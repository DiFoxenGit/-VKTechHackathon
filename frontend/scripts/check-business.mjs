import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {loadModule} from './load-module.mjs';
const {parseBusinessConditions,parseBusinessSettings,businessApiFields,analysisForSlide}=await loadModule('src/business.ts');
const fixture=JSON.parse(await readFile(new URL('./fixtures/business-request.json',import.meta.url),'utf8'));
const settings=parseBusinessSettings(fixture.settings);
const conditions=parseBusinessConditions(fixture.conditions);
const business={settings,conditions,context_source_id:'context'};
const {readSaved,STORAGE_KEY,DEFAULT_BRIEF}=await loadModule('src/storage.ts');
let stored=JSON.stringify({brief:{...DEFAULT_BRIEF,business},decks:[{id:'periods',title:'Q2',slides:[{id:'1',title:'Q2',body:''}],templateId:'tech',brief:{...DEFAULT_BRIEF,business}}]});
globalThis.localStorage={getItem:key=>{assert.equal(key,STORAGE_KEY);return stored;}};
assert.deepEqual(readSaved().brief.business,business);
assert.deepEqual(readSaved().decks[0].brief.business,business);
stored=JSON.stringify({brief:{...DEFAULT_BRIEF,business:{...business,settings:{...settings,current:['','2026-06']}}}});
assert.deepEqual(readSaved().brief.business.settings.current,['','2026-06'],'Incomplete date edits must survive reload without selecting default periods');
assert.throws(()=>parseBusinessSettings({current:['2026-99','2026-99']}));
assert.throws(()=>parseBusinessConditions({...conditions,capacity:{}}));
assert.throws(()=>parseBusinessConditions({...conditions,capacity:{...conditions.capacity,engineers:{value:'3',quote:'three'}}}));
const defines={'import.meta.env.DEV':'false','import.meta.env.VITE_PRESENTATIONS_API_BASE_URL':"'http://api.example/api/v1'"};
globalThis.window={setTimeout,clearTimeout,location:{href:'http://frontend.example/'}};
const {createPresentationService}=await loadModule('src/services/presentationService.ts',defines);
const service=createPresentationService();let requests=[];
const record={id:'deck',title:'Q2',template_id:'tech',variant:'classic',revision:1,business_request:business,deck:{slides:[{content:{title:'Q2',bullets:[]}}]}};
globalThis.fetch=async(url,init)=>{requests.push({url,body:init.body&&JSON.parse(init.body)});return new Response(JSON.stringify(url.endsWith('/generations')?{id:'job',status:'completed',presentation_ids:['deck']}:url.endsWith('/analysis')?{items:[]}:record),{headers:{'Content-Type':'application/json'}});};
const brief={...DEFAULT_BRIEF,text:'Маржа и прибыль по периодам',slideCount:12,business};
await service.analyseMaterials(brief);
const generated=await service.generate(brief,'tech');
for(const request of requests.filter(r=>r.body))for(const [key,value] of Object.entries(businessApiFields(business)))assert.deepEqual(request.body[key],value);
assert.deepEqual(generated.brief.business,business);
const saved=await service.save(generated);
assert.deepEqual(saved.brief.business,business);
assert.deepEqual(analysisForSlide([{analysis_id:'derived',business_view:'quarter_kpi'}],'business:kpi:token'),[{analysis_id:'derived',business_view:'quarter_kpi'}]);
assert.deepEqual(analysisForSlide([{analysis_id:'derived',business_view:'monthly_trend'}],'business:kpi:token'),[]);
assert.equal(requests.at(-1).body.business_request,undefined,'Editor changes cannot replace trusted calculation inputs');
console.log('PASS: business settings/conditions storage, request propagation, server replay and protected editor boundary');
