async (page) => {
  const results = [];
  const check = (condition, name) => { if (!condition) throw new Error(name); results.push(name); };
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({width: 1440, height: 1000});
  let jobStatus = 'queued';
  let requests = 0;
  let polls = 0;
  let failExport = false;
  let templateFailure = false;
  let uploadDelay = 0;
  const template = {id: 'test-tech', name: 'VK Tech', layouts: [{index: 0, name: 'Cover'}]};
  await page.route('**/api/v1/**', async route => {
    const url = new URL(route.request().url());
    const json = body => route.fulfill({json: body});
    if (url.pathname.endsWith('/templates')) {
      if (route.request().method() === 'POST') { await new Promise(r => setTimeout(r, uploadDelay)); return json({...template, id:'uploaded', name:'Мой шаблон'}); }
      return templateFailure ? route.fulfill({status:503,json:{detail:'Недоступен'}}) : json({items:[template]});
    }
    if (url.pathname.endsWith('/generations')) { requests++; return json({id: 'job-1', status: 'queued', progress: 0}); }
    if (url.pathname.endsWith('/jobs/job-1')) {
      polls++;
      return json(jobStatus === 'completed' ? {id:'job-1',status:'completed',presentation_ids:['deck-1'],progress:100} : jobStatus === 'failed' ? {id:'job-1',status:'failed',error:'Не удалось оформить слайды'} : {id:'job-1',status:jobStatus,progress:jobStatus === 'running' ? 45 : 0,stage:'layout_and_audit'});
    }
    if (url.pathname.endsWith('/presentations/deck-1')) return json({id:'deck-1',title:'Проверка UX',template_id:'test-tech',variant:'classic',revision:1,deck:{slides:[{content:{title:'Идея продукта',bullets:['Первый тезис']}},{content:{title:'Результаты',bullets:['Второй тезис']}},{content:{title:'Следующий шаг',bullets:['Третий тезис']}}]}});
    if (url.pathname.includes('/export/')) return failExport ? route.fulfill({status:503,json:{detail:'Экспорт временно недоступен'}}) : route.fulfill({contentType:'application/octet-stream',body:'UX export'});
    if (url.pathname.endsWith('/content-packs')) { await new Promise(r => setTimeout(r, uploadDelay)); return json({id:'pack-1',name:'notes.txt',text:'Материалы для презентации',sha256:'test'}); }
    return route.abort();
  });
  await page.addInitScript(() => localStorage.removeItem('slide-studio:v1'));
  await page.goto(page.url());
  await page.getByRole('button',{name:'Создать презентацию',exact:true}).click();
  await page.getByText('Добавьте хотя бы 20 символов: тему и несколько тезисов.').waitFor();
  check(await page.getByRole('textbox',{name:'Описание презентации'}).evaluate(el => el === document.activeElement), 'Validation focuses brief');
  await page.getByRole('button',{name:'Питч продукта',exact:true}).click();
  await page.screenshot({path:'output/playwright/ux-home-desktop.png'});
  await page.getByRole('button',{name:'Создать презентацию',exact:true}).click();
  await page.getByRole('heading',{name:'Задание в очереди',exact:true}).waitFor();
  check(await page.getByRole('progressbar').getAttribute('aria-valuenow') === null, 'Queue has no fake percent');
  jobStatus = 'running';
  await page.getByRole('progressbar').filter({hasNot:page.locator('nothing')}).waitFor();
  await page.getByRole('heading',{name:'Оформляем и проверяем слайды',exact:true}).waitFor();
  check(await page.getByRole('progressbar').getAttribute('aria-valuenow') === '45', 'Server progress displays 45%');
  check(requests === 1, 'One generation request');
  await page.screenshot({path:'output/playwright/ux-progress-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), 'Mobile progress has no overflow');
  await page.screenshot({path:'output/playwright/ux-progress-mobile.png'});
  await page.getByRole('button',{name:'Прекратить ожидание'}).click();
  await page.getByRole('textbox',{name:'Описание презентации'}).waitFor();
  const pollsAtCancel = polls;
  await page.waitForTimeout(1800);
  check(polls === pollsAtCancel, 'Cancel stops polling');
  check((await page.getByRole('textbox',{name:'Описание презентации'}).inputValue()).length > 20, 'Cancel preserves brief');
  jobStatus = 'failed';
  await page.getByRole('button',{name:'Создать презентацию',exact:true}).click();
  await page.getByText(/Не удалось оформить слайды/).waitFor();
  check(await page.getByRole('button',{name:'Создать презентацию',exact:true}).isEnabled(), 'Failure enables retry');
  jobStatus = 'running';
  await page.getByRole('button',{name:'Создать презентацию',exact:true}).click();
  await page.getByRole('heading',{name:'Оформляем и проверяем слайды',exact:true}).waitFor();
  await page.getByRole('button',{name:'Мои презентации',exact:true}).click();
  jobStatus = 'completed';
  await page.getByText('Готова презентация «Проверка UX»').waitFor();
  check(await page.getByRole('heading',{name:'Мои презентации',exact:true}).isVisible(), 'Completion does not hijack another screen');
  await page.getByRole('button',{name:'Открыть',exact:true}).click();
  await page.getByRole('textbox',{name:'Название презентации'}).waitFor();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), 'Mobile editor has no overflow');
  await page.screenshot({path:'output/playwright/ux-editor-mobile.png'});
  await page.getByRole('button',{name:'Удалить текущий слайд',exact:true}).click();
  await page.getByRole('button',{name:'Вернуть слайд',exact:true}).click();
  check(await page.getByRole('button',{name:'Слайд 1: Идея продукта',exact:true}).count() === 1, 'Slide undo restores slide');
  await page.getByRole('button',{name:'Просмотр',exact:true}).click();
  await page.keyboard.press('ArrowRight');
  await page.getByRole('dialog',{name:'Слайд 2 из 3'}).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('textbox',{name:'Название презентации'}).fill('Проверка сохранения');
  await page.waitForTimeout(750);
  check(await page.evaluate(() => JSON.parse(localStorage.getItem('slide-studio:v1')).decks[0].title) === 'Проверка сохранения', 'Debounced edit persists');
  await page.getByRole('button',{name:'Скачать',exact:true}).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button',{name:/Веб-презентация/}).click();
  check((await download).suggestedFilename().endsWith('.html'), 'Local HTML export downloads');
  await page.getByRole('button',{name:'Закрыть',exact:true}).click();
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:'output/playwright/ux-editor-desktop.png'});
  await page.getByRole('button',{name:'Мои презентации',exact:true}).click();
  await page.getByRole('button',{name:'Новая презентация',exact:true}).click();
  check(await page.getByRole('textbox',{name:'Описание презентации'}).inputValue() === '', 'New presentation clears previous brief');
  await page.getByLabel('Загрузить материалы',{exact:true}).setInputFiles({name:'bad.exe',mimeType:'application/octet-stream',buffer:Buffer.from('invalid')});
  await page.getByText('Поддерживаются TXT, MD, CSV, JSON, DOCX, PPTX и PDF.').waitFor();
  uploadDelay = 1200;
  await page.getByLabel('Загрузить материалы',{exact:true}).setInputFiles({name:'notes.txt',mimeType:'text/plain',buffer:Buffer.from('Материалы')});
  await page.getByRole('heading',{name:/Загружаем материалы|Читаем материалы/}).waitFor();
  await page.getByText('notes.txt',{exact:true}).waitFor();
  await page.getByLabel('Загрузить материалы',{exact:true}).setInputFiles({name:'notes.txt',mimeType:'text/plain',buffer:Buffer.from('Другие материалы')});
  await page.getByRole('heading',{name:/Загружаем материалы|Читаем материалы/}).waitFor();
  await page.getByRole('button',{name:'Мои презентации',exact:true}).click();
  await page.getByRole('button',{name:'Открыть Проверка сохранения',exact:true}).click();
  await page.waitForTimeout(1400);
  check(await page.evaluate(() => (JSON.parse(localStorage.getItem('slide-studio:v1')).brief.contentPackIds || []).length === 0), 'Upload cannot contaminate another brief');
  await page.getByRole('button',{name:'Слайд — на главную'}).click();
  await page.getByRole('button',{name:'Питч продукта',exact:true}).click();
  await page.getByRole('button',{name:'Создать презентацию',exact:true}).click();
  await page.getByRole('button',{name:'Скачать',exact:true}).waitFor();
  await page.getByRole('button',{name:'Скачать',exact:true}).click();
  failExport = true;
  await page.getByRole('button',{name:/PowerPoint/}).click();
  await page.getByRole('dialog').getByText('Экспорт временно недоступен').waitFor();
  check(await page.getByRole('dialog').getByRole('button',{name:/PowerPoint/}).isEnabled(), 'Export failure is visible and retryable');
  await page.getByRole('button',{name:'Закрыть',exact:true}).click();
  templateFailure = true;
  await page.reload();
  await page.getByRole('button',{name:'Подключиться снова',exact:true}).waitFor();
  check(await page.getByRole('button',{name:'Создать презентацию',exact:true}).isDisabled(), 'Unavailable service disables generation');
  templateFailure = false;
  await page.getByRole('button',{name:'Подключиться снова',exact:true}).click();
  await page.getByRole('button',{name:'Создать презентацию',exact:true}).waitFor();
  await page.waitForTimeout(200);
  check(await page.getByRole('button',{name:'Создать презентацию',exact:true}).isEnabled(), 'Reconnect restores generation');
  check(errors.length === 0, `No runtime errors (${errors.join('; ')})`);
  return {passed:results.length,results};
}
